/**
 * Assemble styles.css from styles/*.css, in filename order, and the tile
 * module from assets/tiles/.
 *
 * Background tiles live as WebP or PNG files in assets/tiles/, a light and
 * a dark one per pattern. Obsidian parses a plugin's stylesheet in every
 * window at load, so the tiles stay out of it: this script writes them as
 * data URLs into src/render/tiles.generated.ts, which esbuild bundles into
 * main.js, and the page sets the chosen pattern's two tiles as custom
 * properties (see src/render/backgrounds.ts).
 *
 * The build fails, and writes nothing, when braces do not balance in any
 * partial, when a partial embeds an image, or when a pattern lacks its
 * light or dark tile. Each guard catches a way an edit has broken these
 * files before.
 */

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

/** The repository root: npm runs every script from there. */
const root = process.cwd();
const partialsDir = join(root, "styles");
const tilesDir = join(root, "assets", "tiles");
const TILE_FILE = /^([a-z0-9]+)-(light|dark)\.(webp|png)$/;
const MIME = { webp: "image/webp", png: "image/png" };
/** Where the tile module goes, from the repository root. */
export const TILES_MODULE = join("src", "render", "tiles.generated.ts");

function fail(message) {
  console.error(`build-css: ${message}`);
  process.exit(1);
}

function braceBalance(css) {
  const bare = css.replace(/\/\*[\s\S]*?\*\//g, "").replace(/"[^"]*"/g, '""');
  let depth = 0;
  for (const ch of bare) {
    if (ch === "{") depth++;
    else if (ch === "}" && --depth < 0) return depth;
  }
  return depth;
}

/** The stylesheet the build writes. */
export function assembleCss() {
  const partials = readdirSync(partialsDir).filter((f) => f.endsWith(".css")).sort();
  if (!partials.length) fail("no partials in styles/");

  let css = "";
  for (const name of partials) {
    const text = readFileSync(join(partialsDir, name), "utf8");
    if (braceBalance(text) !== 0) fail(`${name}: unbalanced braces`);
    if (/url\(\s*["']?data:/.test(text)) fail(`${name}: embeds an image; tiles belong in assets/tiles/`);
    css += text;
  }
  return css;
}

/** The tile module's source: every pattern's light and dark tile as a data URL. */
export function assembleTiles() {
  const tiles = new Map();
  for (const file of readdirSync(tilesDir).sort()) {
    const m = TILE_FILE.exec(file);
    if (!m) fail(`assets/tiles/${file}: name it <id>-light or <id>-dark, as WebP or PNG`);
    const [, id, mode, ext] = m;
    const data = readFileSync(join(tilesDir, file)).toString("base64");
    tiles.set(id, { ...tiles.get(id), [mode]: `data:${MIME[ext]};base64,${data}` });
  }
  const lines = [];
  for (const [id, pair] of tiles) {
    if (!pair.light || !pair.dark) fail(`${id}: needs both a light and a dark tile`);
    lines.push(`  ${JSON.stringify(id)}: {\n    light: ${JSON.stringify(pair.light)},\n    dark: ${JSON.stringify(pair.dark)},\n  },`);
  }
  return [
    "// Generated by scripts/build-css.mjs from assets/tiles/. Do not edit; run npm run css.",
    "",
    "/** Each background pattern's tiles as data URLs, by pattern id. */",
    "export const TILES: Readonly<Record<string, { readonly light: string; readonly dark: string }>> = {",
    ...lines,
    "};",
    "",
  ].join("\n");
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const css = assembleCss();
  const tiles = assembleTiles();
  writeFileSync(join(root, "styles.css"), css);
  writeFileSync(join(root, TILES_MODULE), tiles);
  console.log(`build-css: styles.css, ${(css.length / 1024).toFixed(0)} KB; ${TILES_MODULE}, ${(tiles.length / 1024).toFixed(0)} KB`);
}
